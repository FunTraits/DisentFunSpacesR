#' Generate an R script reproducing an analysis
#'
#' Used by the Shiny application to export a stand-alone script that
#' reproduces the analysis outside the app (for archiving with a
#' manuscript).
#'
#' @param p Named list of settings (`data_file`, `trait_info_file`,
#'   `species_col`, `iucn_col`, `sep`, `missing`, `phylo_file`,
#'   `n_phylo_axes`, `ntree`, `cov_cols`, `spaces`, `weighting`, `correction`,
#'   `method`, `nrepet`, `n_axes`, `mantel`, `k`; optionally `engine`,
#'   `eigen`, `keep_dist`, `cores` (large datasets), `status_col`,
#'   `native_label`, `hull_axes` for non-native species).
#' @return A character string.
#' @export
analysis_script <- function(p) {
  dq <- function(x) if (is.null(x) || (length(x) == 1 && is.na(x))) "NULL" else
    paste0("c(", paste0('"', x, '"', collapse = ", "), ")")
  spaces_code <- paste0("list(\n",
    paste0("  `", names(p$spaces), "` = ", vapply(p$spaces, dq, character(1)),
           collapse = ",\n"), "\n)")
  read_data <- if (grepl("\\.xlsx?$", p$data_file, ignore.case = TRUE)) {
    sprintf('traits_raw <- as.data.frame(readxl::read_excel("%s"))', p$data_file)
  } else {
    sprintf('traits_raw <- read.table("%s", header = TRUE, sep = "%s", quote = "\\"",\n                         stringsAsFactors = FALSE, check.names = FALSE)',
            p$data_file, if (p$sep == "\t") "\\t" else p$sep)
  }
  miss <- switch(p$missing,
    keep = "# Missing values kept: handled pairwise by the generalised Gower distance",
    drop = "traits <- drop_incomplete(traits)",
    impute = paste0(
      if (!is.null(p$phylo_file)) sprintf('tree <- ape::read.tree("%s")\n', p$phylo_file) else "",
      if (length(p$cov_cols)) paste0(
        "# predictors of missing values taken from the data table (not traits)\n",
        "predictors <- traits_raw[, ", dq(p$cov_cols), ", drop = FALSE]\n",
        sprintf('rownames(predictors) <- traits_raw[["%s"]]\n', p$species_col)) else "",
      sprintf("traits <- impute_traits(traits%s%s, n_phylo_axes = %d, ntree = %d, seed = %s)",
              if (!is.null(p$phylo_file)) ", phylo = tree" else "",
              if (length(p$cov_cols)) ", covariates = predictors" else "",
              as.integer(p$n_phylo_axes), as.integer(p$ntree), p$seed))
  )
  iucn_code <- if (!is.null(p$iucn_col)) {
    sprintf('iucn <- setNames(traits_raw[["%s"]], traits_raw[["%s"]])', p$iucn_col, p$species_col)
  } else "iucn <- NULL"
  nax <- if (is.null(p$n_axes)) "NULL" else as.character(p$n_axes)
  nn_code <- if (!is.null(p$status_col)) paste0('

## 6. Non-native species
status <- setNames(traits_raw[["', p$status_col, '"]], traits_raw[["', p$species_col, '"]])
nn <- nonnative_all(spaces, status, native = "', if (is.null(p$native_label)) "native" else p$native_label,
'", n_axes = ', nax, ', k = ', p$k, ',
                    hull_axes = ', if (is.null(p$hull_axes)) 4 else p$hull_axes, ', null = "permute", nrep = 999)
summary_nonnative(nn)
compare_nonnative(nn, "FNov", top = 0.1)$pairs
plot_nonnative(spaces[["', utils::tail(names(p$spaces), 1), '"]], status, native = "',
if (is.null(p$native_label)) "native" else p$native_label, '")
') else ""

  paste0(
'# ---------------------------------------------------------------------------
# Functional spaces analysis generated by DisentFunSpaces ', utils::packageVersion("DisentFunSpaces"), '
# (Toussaint et al. 2026, Ecography, doi:10.1002/ecog.08578)
# Date: ', format(Sys.time(), "%Y-%m-%d %H:%M"), '
# ---------------------------------------------------------------------------
library(DisentFunSpaces)
set.seed(', p$seed, ')

## 1. Data and trait description
', read_data, '
trait_info <- read.csv("', p$trait_info_file, '", stringsAsFactors = FALSE)
traits <- prepare_traits(traits_raw, trait_info, species_col = "', p$species_col, '")
traits

## 2. Missing values
', miss, '

## 3. Functional spaces (generalised Gower distance + PCoA)
spaces <- build_spaces(traits,
  spaces = ', spaces_code, ',
  weighting = "', p$weighting, '", correction = "', p$correction, '",
  max_axes = ', if (is.null(p$max_axes)) "NULL" else p$max_axes,
  if (!is.null(p$engine) && p$engine != "ade4") paste0(', engine = "', p$engine, '"') else '',
  if (!is.null(p$eigen) && p$eigen != "full") paste0(', eigen = "', p$eigen, '"') else '',
  if (isFALSE(p$keep_dist)) ', keep_dist = FALSE' else '', ')
spaces
lapply(spaces, plot_space)

## 4. Comparison of spaces (Procrustes tests)
cmp <- compare_spaces(spaces, n_axes = ', nax, ', method = "', p$method, '",
                      nrepet = ', p$nrepet, ', mantel = ', p$mantel,
  if (!is.null(p$cores) && p$cores > 1) paste0(', cores = ', p$cores) else '', ')
cmp
plot_comparison(cmp)

## 5. Species-level metrics (FUn, FSp', if (!is.null(p$iucn_col)) ', FUSE' else '', ')
', iucn_code, '
metrics <- species_metrics_all(spaces, n_axes = ', nax, ', k = ', p$k, ', iucn = iucn)
compare_metrics(metrics, "FUn", top = 0.1)$pairs
', nn_code)
}
